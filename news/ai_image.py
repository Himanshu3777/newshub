"""AI cover photos for NewsHub.

Provider: Pollinations (FLUX model) - a free image-generation API, no key
required. The image is generated from the headline's topic and category only
(never from a publisher photo), so every cover is an original NewsHub asset.

Safety: any failure (timeout, quota, non-JPEG response) returns None and the
caller falls back to the code-drawn SVG illustration. Generated bytes are
stored on the article (cover_jpeg) so each photo is generated exactly once.
"""
import logging, re, urllib.parse
import requests

log = logging.getLogger("newshub.ai_image")
API = "https://image.pollinations.ai/prompt/{prompt}?width=1200&height=630&nologo=true&model=flux&seed={seed}"
STOP = {"the", "and", "for", "with", "from", "that", "this", "will", "over", "after", "before", "says", "said", "news", "live", "update", "updates"}


def build_prompt(article):
    words = [w for w in re.findall(r"[A-Za-z][A-Za-z\-]{2,}", article.title or "") if w.lower() not in STOP][:8]
    topic = " ".join(words) or "current events"
    cat = article.category.name if article.category else "News"
    return ("editorial news photograph style illustration, " + cat.lower() + " story: " + topic +
            ", realistic, dramatic natural lighting, indian context where relevant, "
            "no text, no words, no letters, no watermark, no logo")


def fetch_ai_cover(article, timeout=75):
    """Return JPEG bytes for this article's AI cover, or None on any failure."""
    try:
        url = API.format(prompt=urllib.parse.quote(build_prompt(article)), seed=article.id or 7)
        r = requests.get(url, timeout=timeout, headers={"User-Agent": "NewsHub/1.0 (cover generator)"})
        data = r.content or b""
        if r.status_code == 200 and len(data) > 8000 and data[:2] == b"\xff\xd8":
            return data
        log.warning("AI cover for article %s: bad response status=%s bytes=%s", article.id, r.status_code, len(data))
    except Exception as e:
        log.warning("AI cover for article %s failed: %s", article.id, e)
    return None
